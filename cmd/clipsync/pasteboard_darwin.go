package main

import (
	"errors"
	"runtime"
	"unsafe"

	"github.com/ebitengine/purego"
	"github.com/ebitengine/purego/objc"
)

type macPasteboard struct {
	class, stringClass objc.ID
	push               func() uintptr
	pop                func(uintptr)
	object             func(objc.ID, objc.SEL) objc.ID
	number             func(objc.ID, objc.SEL) uint64
	withObject         func(objc.ID, objc.SEL, objc.ID) objc.ID
	hasObject          func(objc.ID, objc.SEL, objc.ID) bool
	fromUTF8           func(objc.ID, objc.SEL, []byte, int, uintptr) objc.ID
	byteLength         func(objc.ID, objc.SEL, uintptr) int
	toUTF8             func(objc.ID, objc.SEL) *byte
	setString          func(objc.ID, objc.SEL, objc.ID, objc.ID) bool

	general, changes, types, contains, stringForType, utf8, utf8Length, makeString, clear, set objc.SEL
}

func newPasteboard() (pasteboard, error) {
	// Keep AppKit loaded for the lifetime of the process.
	if _, err := purego.Dlopen("/System/Library/Frameworks/AppKit.framework/AppKit", purego.RTLD_LAZY|purego.RTLD_GLOBAL); err != nil {
		return nil, err
	}
	runtime, err := purego.Dlopen("/usr/lib/libobjc.A.dylib", purego.RTLD_LAZY|purego.RTLD_LOCAL)
	if err != nil {
		return nil, err
	}
	b := &macPasteboard{
		class:         objc.ID(objc.GetClass("NSPasteboard")),
		stringClass:   objc.ID(objc.GetClass("NSString")),
		general:       objc.RegisterName("generalPasteboard"),
		changes:       objc.RegisterName("changeCount"),
		types:         objc.RegisterName("types"),
		contains:      objc.RegisterName("containsObject:"),
		stringForType: objc.RegisterName("stringForType:"),
		utf8:          objc.RegisterName("UTF8String"),
		utf8Length:    objc.RegisterName("lengthOfBytesUsingEncoding:"),
		makeString:    objc.RegisterName("stringWithBytes:length:encoding:"),
		clear:         objc.RegisterName("clearContents"),
		set:           objc.RegisterName("setString:forType:"),
	}
	purego.RegisterLibFunc(&b.push, runtime, "objc_autoreleasePoolPush")
	purego.RegisterLibFunc(&b.pop, runtime, "objc_autoreleasePoolPop")
	msg, err := purego.Dlsym(runtime, "objc_msgSend")
	if err != nil {
		return nil, err
	}
	for _, fn := range []any{&b.object, &b.number, &b.withObject, &b.hasObject, &b.fromUTF8, &b.byteLength, &b.toUTF8, &b.setString} {
		purego.RegisterFunc(fn, msg)
	}
	return b, nil
}

func (b *macPasteboard) board() objc.ID {
	return b.object(b.class, b.general)
}

const nsUTF8StringEncoding = 4

func (b *macPasteboard) string(s string) objc.ID {
	return b.fromUTF8(b.stringClass, b.makeString, []byte(s), len(s), nsUTF8StringEncoding)
}

func (b *macPasteboard) pool() func() {
	// Autorelease pools are thread-local even though the clipboard is shared.
	runtime.LockOSThread()
	pool := b.push()
	return func() {
		b.pop(pool)
		runtime.UnlockOSThread()
	}
}

func (b *macPasteboard) changeCount() uint64 {
	unlock := b.pool()
	defer unlock()
	return b.number(b.board(), b.changes)
}

func (b *macPasteboard) read() (string, error) {
	unlock := b.pool()
	defer unlock()
	board := b.board()
	types := b.object(board, b.types)
	for _, kind := range [...]string{"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"} {
		if types != 0 && b.hasObject(types, b.contains, b.string(kind)) {
			return "", nil
		}
	}
	text := b.withObject(board, b.stringForType, b.string("public.utf8-plain-text"))
	if text == 0 {
		return "", nil
	}
	n := b.byteLength(text, b.utf8Length, nsUTF8StringEncoding)
	if ptr := b.toUTF8(text, b.utf8); ptr != nil {
		return string(unsafe.Slice(ptr, n)), nil
	}
	return "", nil
}

func (b *macPasteboard) write(text string) (uint64, error) {
	unlock := b.pool()
	defer unlock()
	board := b.board()
	b.number(board, b.clear)
	if !b.setString(board, b.set, b.string(text), b.string("public.utf8-plain-text")) {
		return 0, errors.New("writing the pasteboard")
	}
	return b.number(board, b.changes), nil
}
