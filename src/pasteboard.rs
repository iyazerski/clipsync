//! The Mac's general pasteboard (the clipboard), through AppKit.
//!
//! macOS has no "clipboard changed" event: tools poll the pasteboard's
//! change count, which is cheap, and read the text only when it moves.

use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;

/// Types that password managers and other apps add to mark a copy that
/// shouldn't leave the Mac or be kept (see nspasteboard.org).
const PRIVATE_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// The general pasteboard's change count: it moves on every copy.
pub fn change_count() -> isize {
    autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount())
}

/// The pasteboard's text, unless there is none or the copy is marked private.
pub fn read() -> Option<String> {
    autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        let private = pasteboard.types().is_some_and(|types| {
            types
                .iter()
                .any(|kind| PRIVATE_TYPES.contains(&kind.to_string().as_str()))
        });
        if private {
            return None;
        }
        // SAFETY: NSPasteboardTypeString is an immutable constant that AppKit
        // sets up before any code runs.
        let kind = unsafe { NSPasteboardTypeString };
        pasteboard.stringForType(kind).map(|text| text.to_string())
    })
}

/// Replace the pasteboard's contents with `text`, and return the new
/// change count.
pub fn write(text: &str) -> isize {
    autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        // SAFETY: as in `read`.
        let kind = unsafe { NSPasteboardTypeString };
        pasteboard.setString_forType(&NSString::from_str(text), kind);
        pasteboard.changeCount()
    })
}
